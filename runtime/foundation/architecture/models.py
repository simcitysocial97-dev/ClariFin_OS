@dataclass(frozen=True, slots=True)
class Architecture:
    """The complete canonical architecture. Read-only, evidence-backed."""

    generated_at: str
    source_artifacts: tuple[str, ...]
    engines: dict[str, Engine]
    engine_modules: dict[str, ImplementationModule]
    detectors: dict[str, Detector]
    facades: dict[str, Facade]
    capabilities: dict[str, Capability]
    routers: dict[str, Router]
    endpoints: dict[str, Endpoint]
    services: dict[str, Service]
    repositories: dict[str, Repository]
    workspaces: dict[str, Workspace]
    components: dict[str, Component]
    mappers: dict[str, Mapper]
    dtos: dict[str, DTO]
    view_models: dict[str, ViewModel]
    artifacts: dict[str, Artifact]
    ownership: Graph
    execution: Graph
    dependency: Graph

    # -- lookups ----------------------------------------------------------
    def engine(self, name_or_id: str) -> Engine | None:
        if name_or_id in self.engines:
            return self.engines[name_or_id]
        for eng in self.engines.values():
            if eng.name == name_or_id:
                return eng
        return None

    def engine_for_path(self, path: str) -> Engine | None:
        """Resolve the OWNING engine of a repository path using evidence.

        Never assumes ``file == engine``: an implementation module resolves to
        its parent engine, and a package directory resolves to the engine root.
        """
        norm = (path or "").replace("\\", "/")
        if not norm:
            return None
        module = self.engine_modules.get(norm) or self.detectors.get(norm)
        if module is not None:
            return self.engines.get(module.engine)
        best: Engine | None = None
        for eng in self.engines.values():
            if eng.owns_path(norm):
                if best is None or len(eng.path) > len(best.path):
                    best = eng
        return best

    def counts(self) -> dict[str, int]:
        return {
            "engines": len(self.engines),
            "engine_modules": len(self.engine_modules),
            "detectors": len(self.detectors),
            "facades": len(self.facades),
            "capabilities": len(self.capabilities),
            "routers": len(self.routers),
            "endpoints": len(self.endpoints),
            "services": len(self.services),
            "repositories": len(self.repositories),
            "workspaces": len(self.workspaces),
            "components": len(self.components),
            "mappers": len(self.mappers),
            "dtos": len(self.dtos),
            "view_models": len(self.view_models),
            "artifacts": len(self.artifacts),
        }
