"""Canonical architecture models — Program 13.2.

These are the ONLY architectural types the Engineering Runtime may reason
about. They are produced exclusively by
:mod:`runtime.foundation.architecture.provider`, which reads the constitutional
artifacts generated by the single architecture discovery pipeline.

Key distinctions (the constitutional model established by Program 13.1):

* An **Engine** is an architectural UNIT identified by a package directory
  (``__init__.py`` is its public API) or, for small cohesive engines, a single
  file. It is the ownership root for its compute functions.
* An **EngineModule** is an implementation file INSIDE an engine. It is owned
  BY the engine and is NEVER an ownership root. ``*.py`` != Engine.
* A **Detector** is a specialised EngineModule that implements a detection
  contract.
* A **Facade** re-exports another engine (parked/legacy or namespace facade).
  It is not an engine.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

