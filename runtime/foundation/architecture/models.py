@dataclass(frozen=True, slots=True)
class ImplementationModule:
    """A non-engine implementation file that belongs to an engine."""

    id: str
    path: str
    engine: str
    node_type: str = "EngineModule"
    classes: tuple[str, ...] = ()
    functions: tuple[str, ...] = ()
    docstring: str = ""

    @property
    def name(self) -> str:
        return self.path.rsplit("/", 1)[-1]

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "path": self.path,
            "engine": self.engine,
            "node_type": self.node_type,
            "classes": list(self.classes),
            "functions": list(self.functions),
            "docstring": self.docstring,
        }


