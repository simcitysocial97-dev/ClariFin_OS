@dataclass(frozen=True, slots=True)
class Engine:
    """A canonical Engine.

    ``style`` is ``package`` or ``single_file``. For package engines ``path``
    is the package DIRECTORY, and ``entry_point`` is its ``__init__.py``.
    Implementation modules are children — never engines.
    """

    id: str
    name: str
    style: str
    path: str
    entry_point: str
    implementation_modules: tuple[str, ...] = ()
    detectors: tuple[str, ...] = ()
    services: tuple[str, ...] = ()
    routers: tuple[str, ...] = ()
    repositories: tuple[str, ...] = ()
    endpoints: tuple[str, ...] = ()
    capabilities: tuple[str, ...] = ()
    tests: tuple[str, ...] = ()
    artifacts: tuple[str, ...] = ()
    migration_status: str = ""
    internal: bool = False
    evidence: dict[str, Any] = field(default_factory=dict)

    @property
    def is_package(self) -> bool:
        return self.style == "package"

    @property
    def has_router(self) -> bool:
        return bool(self.routers)

    @property
    def has_capability(self) -> bool:
        return bool(self.capabilities)

    def owns_path(self, path: str) -> bool:
        """True if ``path`` is this engine's entry point or an owned module."""
        norm = path.replace("\\", "/").rstrip("/")
        if norm == self.entry_point or norm == self.path:
            return True
        if norm in self.implementation_modules or norm in self.detectors:
            return True
        if self.is_package:
            return norm.startswith(self.path.rstrip("/") + "/")
        return False

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "style": self.style,
            "path": self.path,
            "entry_point": self.entry_point,
            "implementation_modules": list(self.implementation_modules),
            "detectors": list(self.detectors),
            "services": list(self.services),
            "routers": list(self.routers),
            "repositories": list(self.repositories),
            "endpoints": list(self.endpoints),
            "capabilities": list(self.capabilities),
            "tests": list(self.tests),
            "artifacts": list(self.artifacts),
            "migration_status": self.migration_status,
            "internal": self.internal,
            "evidence": self.evidence,
        }


